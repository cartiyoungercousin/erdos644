"""R2-core: what family do the winning adversary's answers describe, and is it (7,2)?

(i)  Closure of the policy: an answer is "offered set minus s points of E" or "offered set minus
     s points outside E".  Every k-set with |E \\ K| >= s or |(V \\ E) \\ K| >= s is such an answer
     for a suitable T-request, so the closure is the block-type family on (E, V \\ E) with types
     (i, k - i),  i <= k - s  or  i >= k/4 - g ... i.e. essentially the complete family K_n.
(ii) The 8-block family generated by one concrete line of play (template requests, c = 4g):
     blocks a1..a4, b1, b2, b3, u; types = E and the six answers (all k-sets with these counts).
Both are tested with compute/typefam.py (bad-7-tuple ILP + independent brute-force check).

usage: py candidate.py
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import typefam


def report(name, fam, T):
    tau, tv = fam.tau()
    w = fam.find_bad_tuple(7, time_limit=600)
    if w is None:
        print(f"{name}: n={fam.n} k={fam.r} tau={tau} (T={T}); NO bad 7-tuple -> property (7,2) holds"
              + ("  ** candidate counterexample, verify **" if tau > T + 1 else ""))
    else:
        print(f"{name}: n={fam.n} k={fam.r} tau={tau} (T={T}); bad 7-tuple found, brute-force check {typefam.verify_witness(fam, w)}"
              f" -> NOT a (7,2)-family; edge types used: {sorted(set(w['edge_types']))}")


if __name__ == "__main__":
    # (i) closure of the adversary policy, k = 8, g = 1, c = 4: n = 18, T = 7, s = 3
    k, g, c = 8, 1, 4; s = c - g; nE, nY = k, 3 * k // 4 + c
    types = [(i, k - i) for i in range(max(0, k - nY), k + 1) if (k - i >= s) or (nY - (k - i) >= s) or i == k]
    report("(i) closure of the policy on (E, V-E)", typefam.TypeFamily([nE, nY], types), 3 * k // 4 + g)
    # (ii) one line of play, k = 16, g = 1, c = 4: n = 32, T = 13, s = 3
    # blocks: a1 a2 a3 a4 (4 each) | b1 b2 b3 (5 each) | u (1)
    sizes = [4, 4, 4, 4, 5, 5, 5, 1]
    E = (4, 4, 4, 4, 0, 0, 0, 0)
    # requests jX = B_j + pair; adversary: 1A drops 3 non-E points (from b2), 1B drops 3 E-points
    # requested at 1A (from a1), 2A..3B drop 3 complete points (from b1)
    R1A = (0, 0, 4, 4, 0, 2, 5, 1)
    R1B = (1, 4, 0, 0, 0, 5, 5, 1)
    R2A = (0, 4, 0, 4, 2, 0, 5, 1)
    R2B = (4, 0, 4, 0, 2, 0, 5, 1)
    R3A = (0, 4, 4, 0, 2, 5, 0, 1)
    R3B = (4, 0, 0, 4, 2, 5, 0, 1)
    for t in (E, R1A, R1B, R2A, R2B, R3A, R3B): assert sum(t) == 16, t
    report("(ii) block family of one line of play", typefam.TypeFamily(sizes, [E, R1A, R1B, R2A, R2B, R3A, R3B]), 13)
