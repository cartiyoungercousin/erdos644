r"""Good-seven decider for 2-cell profile families (Sym(X) x Sym(Y)-invariant), with some members FIXED.
[SAT answers: computed exact (explicit seven re-checked by plain code). UNSAT: solver-only (CaDiCaL), validated by
controls against the exact spectrum enumerator.]
V = X + Y, X = {0..nX-1}, Y = {nX..n-1}. The family's co-edges are all sets with profile (|K & X|, |K & Y|) in P.
Question: are there `free` members of the family which, together with the FIXED sets F_1..F_f (explicit point sets),
cover every pair {u,v} of V (u = v allowed)?  (Free members may repeat, which also covers "at most seven".)
Encoding: m[b][p] = point p in free block b; per block a one-hot profile choice, X/Y counts via totalizers;
pair coverage with aux vars. Symmetry breaking (valid: lex-leader for the group generated by swaps of free blocks and
swaps of points with the same (cell, fixed-membership) signature): free blocks in non-increasing lex order, and within
each point class the columns of m in non-increasing lex order.
Usage: py -3.14 sat_profile.py '<json>'  json = {nX, nY, P: [[a,b],...], fixed: [[points],...], free, tag}"""
import sys, json, itertools, time
from pysat.solvers import Cadical153
from pysat.card import ITotalizer
cfg = json.loads(sys.argv[1])
nX, nY, P, fixed, free = cfg['nX'], cfg['nY'], [tuple(p) for p in cfg['P']], [set(f) for f in cfg['fixed']], cfg['free']
n = nX + nY; X = range(nX); Y = range(nX, n)
top = [0]
def new():
    top[0] += 1; return top[0]
m = [[new() for p in range(n)] for b in range(free)]
cls = []
def lex_ge(A, B):  # A >=lex B (bit vectors, True > False)
    e = None
    for i, (a, b) in enumerate(zip(A, B)):
        if e is None: cls.append([a, -b])
        else: cls.append([-e, a, -b])
        if i == len(A) - 1: break
        e2 = new()
        if e is None: cls.extend([[a, b, e2], [-a, -b, e2]])
        else: cls.extend([[-e, a, b, e2], [-e, -a, -b, e2]])
        e = e2
for b in range(free):
    sel = [new() for _ in P]
    cls.append(sel)
    for s1, s2 in itertools.combinations(sel, 2): cls.append([-s1, -s2])
    for part, rng in ((0, X), (1, Y)):
        L = len(rng)
        # pysat totalizers propagate one way only (inputs -> outputs), so use one on the literals (upper bound) and one
        # on their negations (lower bound): s -> not up[t] gives count <= t; s -> not dn[L - t] gives count >= t.
        up = ITotalizer(lits=[m[b][p] for p in rng], ubound=L, top_id=top[0]); cls.extend(up.cnf.clauses); top[0] = max(top[0], up.top_id)
        dn = ITotalizer(lits=[-m[b][p] for p in rng], ubound=L, top_id=top[0]); cls.extend(dn.cnf.clauses); top[0] = max(top[0], dn.top_id)
        for s, pr in zip(sel, P):
            t = pr[part]
            if t > L: cls.append([-s]); continue
            if t < L: cls.append([-s, -up.rhs[t]])
            if t > 0: cls.append([-s, -dn.rhs[L - t]])
pairs = [(u, v) for u in range(n) for v in range(u, n)]
for (u, v) in pairs:
    if any(u in F and v in F for F in fixed): continue
    ws = []
    for b in range(free):
        if u == v: ws.append(m[b][u]); continue
        w = new(); cls.extend([[-w, m[b][u]], [-w, m[b][v]]]); ws.append(w)
    cls.append(ws)
# symmetry breaking
for b in range(free - 1): lex_ge([m[b][p] for p in range(n)], [m[b + 1][p] for p in range(n)])
sig = {}
for p in range(n): sig.setdefault((p < nX, tuple(p in F for F in fixed)), []).append(p)
for ps in sig.values():
    for p, q in zip(ps, ps[1:]): lex_ge([m[b][p] for b in range(free)], [m[b][q] for b in range(free)])
t0 = time.time()
with Cadical153(bootstrap_with=cls) as s:
    sat = s.solve(); model = set(l for l in s.get_model() if l > 0) if sat else None
dt = time.time() - t0
tag = cfg.get('tag', '')
if not sat:
    print(f"[{tag}] UNSAT: no good seven ({dt:.1f}s) [solver-only]"); sys.exit()
blocks = [{p for p in range(n) if m[b][p] in model} for b in range(free)]
seven = fixed + blocks
ok = all((len(B & set(X)), len(B & set(Y))) in P for B in blocks)
ok &= all(any(u in A and v in A for A in seven) for (u, v) in pairs)
print(f"[{tag}] SAT: good seven found ({dt:.1f}s), plain-code re-check {ok}; free profiles "
      f"{[(len(B & set(X)), len(B & set(Y))) for B in blocks]}")
print("  SEVEN", json.dumps([sorted(A) for A in seven]))
